def get_text(lang: str, key: str, **kwargs) -> str:
    """Obtiene el texto traducido para el idioma dado, con fallback a 'en'."""
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    txt = lang_dict.get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        try:
            return txt.format(**kwargs)
        except Exception:
            return txt
    return txt
